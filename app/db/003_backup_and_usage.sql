DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='ws_backup') THEN
   CREATE ROLE ws_backup LOGIN NOSUPERUSER BYPASSRLS NOCREATEDB NOCREATEROLE;
 END IF;
END $$;
GRANT USAGE ON SCHEMA public TO ws_backup;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO ws_backup;
GRANT SELECT ON ALL SEQUENCES IN SCHEMA public TO ws_backup;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO ws_backup;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON SEQUENCES TO ws_backup;
ALTER TABLE usage_ledger ADD COLUMN failed boolean NOT NULL DEFAULT false;
